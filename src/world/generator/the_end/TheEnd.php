<?php

declare(strict_types=1);

namespace pocketmine\world\generator\the_end;

use pocketmine\block\Block;
use pocketmine\block\VanillaBlocks;
use pocketmine\data\bedrock\BiomeIds;
use pocketmine\world\ChunkManager;
use pocketmine\world\format\Chunk;
use pocketmine\world\format\PalettedBlockArray;
use pocketmine\world\format\SubChunk;
use pocketmine\world\generator\Generator;
use pocketmine\world\World;

/** Deterministic End terrain: central island, dragon pillars and outer islands. */
class TheEnd extends Generator{
	public function generateChunk(ChunkManager $world, int $chunkX, int $chunkZ) : void{
		$chunk = new Chunk([], false);
		$biomes = new PalettedBlockArray(BiomeIds::THE_END);
		foreach($chunk->getSubChunks() as $y => $_){
			$chunk->setSubChunk($y, new SubChunk(Block::EMPTY_STATE_ID, [], clone $biomes));
		}

		$endStone = VanillaBlocks::END_STONE()->getStateId();
		$obsidian = VanillaBlocks::OBSIDIAN()->getStateId();
		$ironBars = VanillaBlocks::IRON_BARS()->getStateId();
		$pillars = self::getPillars();
		for($x = 0; $x < Chunk::EDGE_LENGTH; ++$x){
			for($z = 0; $z < Chunk::EDGE_LENGTH; ++$z){
				$worldX = ($chunkX * Chunk::EDGE_LENGTH) + $x;
				$worldZ = ($chunkZ * Chunk::EDGE_LENGTH) + $z;
				$distance = sqrt(($worldX * $worldX) + ($worldZ * $worldZ));
				$radius = 96.0 + (9.0 * sin($worldX * 0.035) * cos($worldZ * 0.031));
				if($distance <= $radius){
					$surface = 63 + (int) round(2.0 * sin($worldX * 0.11) * cos($worldZ * 0.09));
					$depth = max(54, $surface - 9);
					for($y = $depth; $y <= $surface; ++$y){
						$chunk->setBlockStateId($x, $y, $z, $endStone);
					}
				}else{
					$this->generateOuterIslandColumn($chunk, $x, $z, $worldX, $worldZ, $endStone);
				}
				foreach($pillars as [$pillarX, $pillarZ, $height, $caged]){
					$dx = $worldX - $pillarX;
					$dz = $worldZ - $pillarZ;
					if(($dx * $dx) + ($dz * $dz) <= 4){
						for($y = 64; $y <= 64 + $height; ++$y){
							$chunk->setBlockStateId($x, $y, $z, $obsidian);
						}
						if(($dx * $dx) + ($dz * $dz) <= 9){
							$chunk->setBlockStateId($x, 65 + $height, $z, $obsidian);
						}
						if($caged && abs($dx) === 2 && abs($dz) <= 2){
							for($y = 64 + $height - 3; $y <= 64 + $height; ++$y){
								$chunk->setBlockStateId($x, $y, $z, $ironBars);
							}
						}elseif($caged && abs($dz) === 2 && abs($dx) <= 2){
							for($y = 64 + $height - 3; $y <= 64 + $height; ++$y){
								$chunk->setBlockStateId($x, $y, $z, $ironBars);
							}
						}
					}
				}
			}
		}
		$world->setChunk($chunkX, $chunkZ, $chunk);
	}

	public function populateChunk(ChunkManager $world, int $chunkX, int $chunkZ) : void{}

	/** Repairs the central island in End worlds generated by earlier BetterPMMP builds. */
	public static function upgradeArenaChunk(World $world, int $chunkX, int $chunkZ) : void{
		$chunk = $world->getChunk($chunkX, $chunkZ);
		if($chunk === null){
			return;
		}
		$endStone = VanillaBlocks::END_STONE()->getStateId();
		$obsidian = VanillaBlocks::OBSIDIAN()->getStateId();
		$ironBars = VanillaBlocks::IRON_BARS()->getStateId();
		$pillars = self::getPillars();
		for($localX = 0; $localX < Chunk::EDGE_LENGTH; ++$localX){
			for($localZ = 0; $localZ < Chunk::EDGE_LENGTH; ++$localZ){
				$x = ($chunkX * Chunk::EDGE_LENGTH) + $localX;
				$z = ($chunkZ * Chunk::EDGE_LENGTH) + $localZ;
				$distance = sqrt(($x * $x) + ($z * $z));
				$radius = 96.0 + (9.0 * sin($x * 0.035) * cos($z * 0.031));
				if($distance <= $radius){
					$surface = 63 + (int) round(2.0 * sin($x * 0.11) * cos($z * 0.09));
					for($y = max(54, $surface - 9); $y <= $surface; ++$y){
						$chunk->setBlockStateId($localX, $y, $localZ, $endStone);
					}
				}
				foreach($pillars as [$pillarX, $pillarZ, $height, $caged]){
					$dx = $x - $pillarX;
					$dz = $z - $pillarZ;
					$distanceSquared = ($dx * $dx) + ($dz * $dz);
					if($distanceSquared <= 4){
						for($y = 64; $y <= 64 + $height; ++$y){
							$chunk->setBlockStateId($localX, $y, $localZ, $obsidian);
						}
						if($distanceSquared <= 9){
							$chunk->setBlockStateId($localX, 65 + $height, $localZ, $obsidian);
						}
						if($caged && ((abs($dx) === 2 && abs($dz) <= 2) || (abs($dz) === 2 && abs($dx) <= 2))){
							for($y = 64 + $height - 3; $y <= 64 + $height; ++$y){
								$chunk->setBlockStateId($localX, $y, $localZ, $ironBars);
							}
						}
					}
				}
			}
		}
		$world->setChunk($chunkX, $chunkZ, $chunk);
	}

	/** @return list<array{int, int, int, bool}> */
	public static function getPillars() : array{
		$result = [];
		for($i = 0; $i < 10; ++$i){
			$angle = (2 * M_PI * $i) / 10;
			$radius = 45;
			$result[] = [
				(int) round(cos($angle) * $radius),
				(int) round(sin($angle) * $radius),
				24 + (($i * 17) % 18),
				$i === 2 || $i === 7
			];
		}
		return $result;
	}

	private function generateOuterIslandColumn(Chunk $chunk, int $localX, int $localZ, int $worldX, int $worldZ, int $endStone) : void{
		$cellX = (int) floor($worldX / 128);
		$cellZ = (int) floor($worldZ / 128);
		$centerX = ($cellX * 128) + 64;
		$centerZ = ($cellZ * 128) + 64;
		$originDistance = sqrt(($centerX * $centerX) + ($centerZ * $centerZ));
		if($originDistance < 420 || $originDistance > 1500){
			return;
		}
		$hash = abs(sin(($cellX * 127.1) + ($cellZ * 311.7)) * 43758.5453);
		if($hash < 0.42){
			return;
		}
		$radiusX = 12 + (int) ($hash * 23);
		$radiusZ = 10 + (int) (abs(cos(($cellX * 73.3) - ($cellZ * 19.1))) * 22);
		$dx = ($worldX - $centerX) / $radiusX;
		$dz = ($worldZ - $centerZ) / $radiusZ;
		$shape = ($dx * $dx) + ($dz * $dz);
		if($shape > 1){
			return;
		}
		$surface = 54 + (int) ($hash * 17);
		$thickness = max(3, (int) round((1 - $shape) * 12));
		for($y = $surface - $thickness; $y <= $surface; ++$y){
			$chunk->setBlockStateId($localX, $y, $localZ, $endStone);
		}
	}
}
